import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {cpSync,copyFileSync,writeFileSync,readFileSync,mkdirSync,readdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const offline=spawnSync(process.execPath,[path.join(root,'scripts/build-offline-shell.mjs')],{cwd:root,stdio:'inherit'});
if(offline.status!==0)process.exit(offline.status||1);
const result=spawnSync(process.execPath,[path.join(root,'node_modules/vinext/dist/cli.js'),'build'],{cwd:root,stdio:'inherit'});
if(result.status!==0)process.exit(result.status||1);
const output=path.join(root,'dist/standalone');
copyFileSync(path.join(root,'portable/app.cjs'),path.join(output,'app.cjs'));
cpSync(path.join(root,'portable'),path.join(output,'operations'),{recursive:true});
cpSync(path.join(root,'drizzle'),path.join(output,'drizzle'),{recursive:true});
const migrations=readdirSync(path.join(root,'drizzle')).filter(name=>/^\d+.*\.sql$/.test(name)).sort().map(name=>({name,sha256:createHash('sha256').update(readFileSync(path.join(root,'drizzle',name))).digest('hex')}));
writeFileSync(path.join(output,'drizzle/manifest.json'),JSON.stringify({format:'yourrest-migrations-v1',files:migrations},null,2)+'\n');
const entry=path.join(output,'server.js');let source=readFileSync(entry,'utf8');
const old='const port = Number.parseInt(process.env.PORT ?? "3000", 10);';
if(!source.includes(old))throw Error('Unexpected standalone entry; review socket configuration.');
source=source.replace(old,'const portValue=process.env.PORT || "3000";\nconst port=portValue.startsWith("/")?portValue:Number.parseInt(portValue,10);\nif(typeof port==="number"&&(!Number.isInteger(port)||port<0||port>65535))throw Error("Invalid listen port");');
writeFileSync(entry,source);
console.log(JSON.stringify({standalone:output,socketSupport:true}));
